import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { expiredRecords } from "../../addon/src/core/constants";
import type { ProfessionData, Skill } from "../../addon/src/data/generated/professions";
import { fetchCmangos, parseSqlTable, readSqlFile } from "../route-builder/ingest/cmangos";
import { parseCsv } from "../route-builder/ingest/csv";
import { cachedSnapshot } from "../route-builder/ingest/questie";
import type { QuestieSnapshot } from "../route-builder/ingest/snapshot";
import { CMANGOS_CLASSIC_DB, QUESTIE_DB, WAGO_DB2 } from "../route-builder/sources";
import { buildProfessions, objectiveItems, type LootRow, type ProfessionNotes } from "./professions";

const OUTPUT_FILE = join("addon", "src", "data", "generated", "professions.ts");
const REPORT_FILE = join("data", "professions", "report.md");
const WAGO_DIR = join("vendor", "wago");
const VERIFIED_ON = "2026-11-28";
const LOVE_POTION = 4201;

const INTERFACE_TEXT = `export type Skill =
  | "herbalism"
  | "mining"
  | "skinning"
  | "fishing"
  | "alchemy"
  | "blacksmithing"
  | "enchanting"
  | "engineering"
  | "leatherworking"
  | "tailoring"
  | "cooking"
  | "firstAid";

export interface ProfessionItem {
  gather: Skill[];
  craft: Skill[];
  // Item class 7 (Trade Goods) in QuestieDB.
  tradeGood: boolean;
}

// Only the profession items among QuestieDB quest item objectives, bound items left out (not on the auction house).
export interface ProfessionData {
  source: { questieDb: string; cmangosCommit: string; wagoBuild: string; verifiedOn: string; expiresOn: string };
  items: Record<number, ProfessionItem>;
  // Herb and mining nodes among those items' QuestieDB objectDrops.
  nodes: Record<number, Skill>;
  // Creatures whose skinning loot holds the item.
  skinned: Record<number, number[]>;
  auctioneers: { npcId: number; faction: "A" | "H" | "AH" }[];
  // Rank spells (Apprentice to Artisan) per profession, for IsPlayerSpell.
  skillSpells: Record<Skill, number[]>;
}
`;

function wago(table: string): { rows: Record<string, string>[]; file: string } {
  const file = join(WAGO_DIR, `${table}-${WAGO_DB2.build}.csv`);
  return { rows: parseCsv(readFileSync(file, "utf8"), file), file };
}

function loot(sql: string, file: string, table: string): LootRow[] {
  return parseSqlTable(sql, file, table, ["entry", "item", "mincountOrRef"]).map((row) => {
    const count = row.int("mincountOrRef");
    return { entry: row.int("entry"), item: row.int("item"), ref: count < 0 ? -count : 0 };
  });
}

function entries<T>(record: Record<number, T>): [number, T][] {
  return Object.keys(record)
    .map(Number)
    .sort((a, b) => a - b)
    .map((id) => [id, record[id]]);
}

export function renderProfessions(data: ProfessionData): string {
  const lines = [
    "// Generated by tools/gen-professions — do not edit",
    `// QuestieDB ${data.source.questieDb}, cmangos classic-db ${data.source.cmangosCommit}, wago.tools DB2 build ${data.source.wagoBuild}; verified on ${data.source.verifiedOn}.`,
    INTERFACE_TEXT,
    "export const PROFESSIONS: ProfessionData = {",
    `  source: ${JSON.stringify(data.source)},`,
    "  items: {",
    ...entries(data.items).map(([id, item]) => `    [${id}]: ${JSON.stringify(item)},`),
    "  },",
    "  nodes: {",
    ...entries(data.nodes).map(([id, skill]) => `    [${id}]: "${skill}",`),
    "  },",
    "  skinned: {",
    ...entries(data.skinned).map(([id, creatures]) => `    [${id}]: [${creatures.join(", ")}],`),
    "  },",
    "  auctioneers: [",
    ...data.auctioneers.map((a) => `    ${JSON.stringify(a)},`),
    "  ],",
    "  skillSpells: {",
    ...Object.entries(data.skillSpells).map(([skill, spells]) => `    ${skill}: [${spells.join(", ")}],`),
    "  },",
    "};",
    "",
  ];
  return lines.join("\n");
}

function itemName(s: QuestieSnapshot, id: number): string {
  return `${id} ${s.items[id]?.name ?? "?"}`;
}

function renderReport(data: ProfessionData, notes: ProfessionNotes, s: QuestieSnapshot): string {
  const items = entries(data.items);
  const count = (keep: (skills: Skill[]) => boolean, pick: "gather" | "craft"): number => items.filter(([, item]) => keep(item[pick])).length;
  const skills = Object.keys(data.skillSpells) as Skill[];
  const quest = s.quests[LOVE_POTION];
  const lovePotion = objectiveItems({ ...s, quests: quest == null ? {} : { [LOVE_POTION]: quest } }).map((id) => {
    const item = data.items[id];
    return `- ${itemName(s, id)}: ${item == null ? "not a profession item (unchanged)" : `gather ${item.gather.join(", ") || "none"}; craft ${item.craft.join(", ") || "none"}; trade good ${item.tradeGood ? "yes" : "no"}`}`;
  });
  const list = (ids: number[]): string[] => (ids.length === 0 ? ["None.", ""] : [...ids.map((id) => `- ${itemName(s, id)}`), ""]);
  return [
    "# Professions report",
    "",
    `Generated by \`npm run gen:professions\` from QuestieDB ${data.source.questieDb}, cmangos classic-db ${data.source.cmangosCommit} and wago.tools DB2 build ${data.source.wagoBuild} (verified on ${data.source.verifiedOn}, expires on ${data.source.expiresOn}).`,
    "",
    "## Counts",
    "",
    `- Quest item objectives in QuestieDB: ${notes.objectiveItems}`,
    `- Profession items: ${items.length} (trade goods: ${items.filter(([, item]) => item.tradeGood).length})`,
    "",
    "| Skill | Gathered | Crafted | Rank spells |",
    "|---|---|---|---|",
    ...skills.map((skill) => `| ${skill} | ${count((list) => list.includes(skill), "gather")} | ${count((list) => list.includes(skill), "craft")} | ${data.skillSpells[skill].join(", ")} |`),
    "",
    `- Gathering nodes: ${Object.keys(data.nodes).length}; skinned items: ${Object.keys(data.skinned).length} (${Object.values(data.skinned).reduce((n, c) => n + c.length, 0)} creatures)`,
    `- Auctioneers: ${data.auctioneers.length} (A ${data.auctioneers.filter((a) => a.faction === "A").length}, H ${data.auctioneers.filter((a) => a.faction === "H").length}, both ${data.auctioneers.filter((a) => a.faction === "AH").length})`,
    `- Lock types (from the OPEN_LOCK effect of the rank spells): ${Object.entries(notes.lockTypes).map(([type, skill]) => `${type} = ${skill}`).join(", ")}`,
    "",
    "## The Love Potion (4201)",
    "",
    ...lovePotion,
    "",
    "## Left out: bound (bind on pickup or quest item)",
    "",
    ...list(notes.bound),
    "## Left out: no bonding in cmangos item_template",
    "",
    ...list(notes.unknownBonding),
    "## Auctioneers without spawns (left out)",
    "",
    ...list(notes.auctioneersWithoutSpawns),
    "## Auctioneers with no friendlyToFaction (kept for both factions)",
    "",
    ...(notes.neutralAuctioneers.length === 0 ? ["None.", ""] : [...notes.neutralAuctioneers.map((id) => `- ${id} ${s.npcs[id]?.name ?? "?"}`), ""]),
    "## Nodes absent from cmangos, classified by the name of a cmangos node",
    "",
    ...(notes.nodesByName.length === 0 ? ["None.", ""] : [...notes.nodesByName.map((id) => `- ${id} ${s.objects[id]?.name ?? "?"}: ${data.nodes[id]}`), ""]),
    "## Object sources no longer used (not a herb or mining node)",
    "",
    ...(notes.droppedObjects.length === 0 ? ["None.", ""] : [...notes.droppedObjects.map((d) => `- ${itemName(s, d.itemId)}: ${d.objects.join(", ")}`), ""]),
  ].join("\n");
}

function write(path: string, content: string): void {
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, content);
  console.log(`wrote ${path} (${Buffer.byteLength(content)} bytes)`);
}

async function main(): Promise<void> {
  const today = new Date().toISOString().slice(0, 10);
  const expired = expiredRecords({ CMANGOS_CLASSIC_DB, QUESTIE_DB, WAGO_DB2 }, today);
  if (expired.length > 0) throw new Error(`gen:professions: expired dated sources on ${today}, verify and renew them: ${expired.join(", ")}`);
  const snapshot = await cachedSnapshot();
  const cmangosFile = fetchCmangos();
  const sql = readSqlFile(cmangosFile);
  const { data, notes } = buildProfessions({
    skillLines: wago("SkillLine").rows,
    abilities: wago("SkillLineAbility").rows,
    effects: wago("SpellEffect").rows,
    locks: wago("Lock").rows,
    gameObjects: parseSqlTable(sql, cmangosFile, "gameobject_template", ["entry", "type", "data0", "name"]).map((r) => ({ entry: r.int("entry"), type: r.int("type"), data0: r.int("data0"), name: String(r.value("name")) })),
    creatures: parseSqlTable(sql, cmangosFile, "creature_template", ["Entry", "SkinningLootId"]).map((r) => ({ entry: r.int("Entry"), skinningLootId: r.int("SkinningLootId") })),
    skinningLoot: loot(sql, cmangosFile, "skinning_loot_template"),
    fishingLoot: loot(sql, cmangosFile, "fishing_loot_template"),
    referenceLoot: loot(sql, cmangosFile, "reference_loot_template"),
    bonding: new Map(parseSqlTable(sql, cmangosFile, "item_template", ["entry", "bonding"]).map((r) => [r.int("entry"), r.int("bonding")])),
    snapshot,
  });
  const empty = Object.entries(data.skillSpells).filter(([, spells]) => spells.length === 0);
  if (empty.length > 0) throw new Error(`gen:professions: no rank spell for ${empty.map(([skill]) => skill).join(", ")}`);
  if (data.auctioneers.length === 0) throw new Error("gen:professions: no auctioneer in the QuestieDB snapshot");
  const full: ProfessionData = {
    source: {
      questieDb: QUESTIE_DB.tag,
      cmangosCommit: CMANGOS_CLASSIC_DB.commit,
      wagoBuild: WAGO_DB2.build,
      verifiedOn: VERIFIED_ON,
      expiresOn: [CMANGOS_CLASSIC_DB.expiresOn, QUESTIE_DB.expiresOn, WAGO_DB2.expiresOn].sort()[0],
    },
    ...data,
  };
  write(OUTPUT_FILE, renderProfessions(full));
  write(REPORT_FILE, renderReport(full, notes, snapshot));
}

if (process.argv[1]?.endsWith("main.ts")) {
  main().catch((error: unknown) => {
    console.error(error instanceof Error ? error.message : String(error));
    process.exitCode = 1;
  });
}

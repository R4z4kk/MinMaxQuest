import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { ACCESS_CHAINS } from "../../addon/src/access/chains";
import { expiredRecords } from "../../addon/src/core/constants";
import { loadInstanceTypes } from "../route-builder/ingest/instances";
import { cachedSnapshot } from "../route-builder/ingest/questie";
import type { QuestieSnapshot } from "../route-builder/ingest/snapshot";
import { ATTUNE, QUESTIE_DB, WAGO_DB2 } from "../route-builder/sources";
import { parseAttune, readAttuneFiles, readAttuneToc, readAttuneVersion, type AttuneNotes } from "./attune";
import { crossCheck, type CrossCheckReport, type StepRef } from "./crosscheck";
import type { AccessData, AccessEntry } from "./types";

const OUTPUT_FILE = join("addon", "src", "data", "generated", "access.ts");
const REPORT_FILE = join("data", "access", "report.md");
const TYPES_FILE = join("tools", "access-import", "types.ts");
const FACTIONS: AccessEntry["faction"][] = ["A", "H", "AH"];
const GROUPS: AccessEntry["group"][] = ["dungeon", "raid", "key", "misc"];

function renderAccess(data: AccessData, types: string, today: string): string {
  const lines = [
    "// Generated by tools/access-import — do not edit",
    `// ${ATTUNE.source}, version ${data.source.version}, reused with the user's consent (Attune declares no license);`,
    `// cross-checked and completed with QuestieDB ${data.source.questieDb}. Generated on ${today}.`,
    types.trimEnd(),
    "",
    "export const ACCESS: AccessData = {",
    `  source: ${JSON.stringify(data.source)},`,
    "  entries: [",
  ];
  for (const { steps, ...head } of data.entries) {
    lines.push(`    ${JSON.stringify(head).slice(0, -1)},"steps":[`);
    for (const step of steps) lines.push(`      ${JSON.stringify(step)},`);
    lines.push("    ]},");
  }
  lines.push("  ],", "};", "");
  return lines.join("\n");
}

function bullets(items: string[], empty = "None."): string[] {
  return items.length === 0 ? [empty, ""] : [...items.map((item) => `- ${item}`), ""];
}

function renderReport(data: AccessData, report: CrossCheckReport, notes: AttuneNotes, s: QuestieSnapshot, today: string): string {
  const entryName = new Map(data.entries.map((e) => [e.id, `${e.id} ${e.name.enUS} (${e.faction})`]));
  const name = (id: string): string => entryName.get(id) ?? id;
  const quest = (id: number): string => {
    const value = s.quests[id]?.name;
    return typeof value === "string" ? `${id} ${value}` : String(id);
  };
  const stepLine = (r: StepRef): string => `${name(r.entry)}, step ${r.step}: ${r.ref}`;
  const stepQuestLine = (r: StepRef & { questFaction: string }): string => `${name(r.entry)}, step ${r.step}: quest ${quest(r.ref)} is ${r.questFaction}`;

  const count = (group: AccessEntry["group"], faction: AccessEntry["faction"]): number =>
    data.entries.filter((e) => e.group === group && e.faction === faction).length;
  const totals = [
    "| Group | A | H | AH | Entries | Steps |",
    "|---|---|---|---|---|---|",
    ...GROUPS.map((group) => {
      const entries = data.entries.filter((e) => e.group === group);
      return `| ${group} | ${FACTIONS.map((f) => count(group, f)).join(" | ")} | ${entries.length} | ${entries.reduce((n, e) => n + e.steps.length, 0)} |`;
    }),
    `| all | ${FACTIONS.map((f) => data.entries.filter((e) => e.faction === f).length).join(" | ")} | ${data.entries.length} | ${data.entries.reduce((n, e) => n + e.steps.length, 0)} |`,
    "",
  ];

  return [
    "# Access import report",
    "",
    `Generated on ${today} by \`npm run gen:access\` from Attune ${data.source.version} and QuestieDB ${data.source.questieDb}.`,
    "Review this report with the diff of `addon/src/data/generated/access.ts` before merging.",
    "",
    "## Totals",
    "",
    ...totals,
    `Completions: ${report.missingDungeons.length} dungeon entries and ${report.addedQuests.length} dungeon quests added from QuestieDB.`,
    "",
    "## Attune quest ids absent from QuestieDB",
    "",
    "Kept in the data: QuestieDB may lag behind.",
    "",
    ...bullets(report.unknownQuests.map(stepLine)),
    "## Attune item ids absent from the QuestieDB snapshot",
    "",
    "The snapshot only holds items that QuestieDB quests reference, so an item listed here may still exist in the game.",
    "",
    ...bullets(report.unknownItems.map(stepLine)),
    "## Faction conflicts",
    "",
    ...bullets(report.factionConflicts.map(stepQuestLine)),
    "## One-faction quests in entries for both factions",
    "",
    ...bullets(report.oneSidedInBoth.map(stepQuestLine)),
    "## Party dungeons missing from Attune (added)",
    "",
    "Their frFR name is the enUS name from QuestieDB: to translate.",
    "",
    ...bullets(report.missingDungeons.map((d) => `${d.areaId} ${d.name} (${d.faction}) -> ${d.entry}`)),
    "## Party dungeons without QuestieDB quests (not added)",
    "",
    ...bullets(report.questlessDungeons.map((d) => `${d.areaId} ${d.name}`)),
    "## Attune dungeons matched to no QuestieDB party dungeon",
    "",
    "None of their quests has a party dungeon as `zoneOrSort`; no quest was added to them.",
    "",
    ...bullets(report.unmatchedAttuneDungeons.map(name)),
    "## Dungeon quests added from QuestieDB",
    "",
    ...bullets(report.addedQuests.map((q) => `${name(q.entry)}: quest ${quest(q.quest)}`)),
    "## Class dungeon quests not added",
    "",
    ...bullets(report.skippedClassQuests.map((q) => `${q.areaId} ${s.dungeons[q.areaId].name}: quest ${quest(q.quest)}`)),
    "## Addon access chains",
    "",
    ...bullets(report.chains.map((c) => (c.mergedInto.length > 0 ? `${c.id}: found in Attune ${c.mergedInto.map(name).join(", ")}` : `${c.id}: absent from Attune, kept`))),
    "## Attune data notes",
    "",
    "Skipped entries (group not imported; `Attune_Data.noattunes`, the raids without attunement, is not read either):",
    "",
    ...bullets(notes.skippedEntries),
    "Dropped links to another Attune entry (FOLLOWS remapped across them, like spacers):",
    "",
    ...bullets(notes.droppedSteps),
    "Dropped FOLLOWS references:",
    "",
    ...bullets(notes.droppedFollows),
    "Steps whose FOLLOWS is an OR in Attune (kept as a plain list):",
    "",
    ...bullets(notes.orFollows),
    "Steps without a numeric ref in Attune (ref 0):",
    "",
    ...bullets(notes.placeholderRefs),
    "Names without a frFR translation in Attune (enUS used, as AceLocale does):",
    "",
    ...bullets(notes.frenchFallbacks),
  ].join("\n");
}

function write(path: string, content: string): void {
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, content);
  console.log(`wrote ${path} (${Buffer.byteLength(content)} bytes)`);
}

async function main(): Promise<void> {
  const today = new Date().toISOString().slice(0, 10);
  const expired = expiredRecords({ ATTUNE, QUESTIE_DB, WAGO_DB2 }, today);
  if (expired.length > 0) throw new Error(`gen:access: expired dated sources on ${today}, verify and renew them: ${expired.join(", ")}`);
  const version = readAttuneVersion(readAttuneToc(ATTUNE.path));
  if (version !== ATTUNE.version) {
    throw new Error(`gen:access: ${ATTUNE.path} is Attune ${version} but ATTUNE pins ${ATTUNE.version}; review the new data, then update ATTUNE in tools/route-builder/sources.ts`);
  }
  const attune = await parseAttune(readAttuneFiles(ATTUNE.path));
  const snapshot = await cachedSnapshot();
  const { entries, report } = crossCheck({ entries: attune.entries, snapshot, instanceTypes: loadInstanceTypes(), chains: ACCESS_CHAINS });
  const data: AccessData = {
    source: { name: "Attune", version, questieDb: QUESTIE_DB.tag, verifiedOn: ATTUNE.verifiedOn, expiresOn: ATTUNE.expiresOn },
    entries,
  };
  write(OUTPUT_FILE, renderAccess(data, readFileSync(TYPES_FILE, "utf8"), today));
  write(REPORT_FILE, renderReport(data, report, attune.notes, snapshot, today));
}

main().catch((error: unknown) => {
  console.error(error instanceof Error ? error.message : String(error));
  process.exitCode = 1;
});
